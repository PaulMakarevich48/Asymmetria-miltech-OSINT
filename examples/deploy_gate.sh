#!/bin/bash
# Гейт выкатки: правка «критического пути» выкатывается только после зелёного прогона лаборатории.
#
#   deploy_gate.sh REPO FROM TO   → 0 — можно (печатает, каким прогоном), 1 — нельзя
#
# Лаборатория — полный прогон дня без публикации; зелёный прогон кладёт отметку ok_<коммит>.
# Годится отметка ЛЮБОГО коммита, после которого файлы критического пути не менялись: иначе
# каждый коммит с документами требовал бы нового платного прогона.
#
# Урок: `git diff | grep -q` под `set -o pipefail` врёт. grep выходит на первом совпадении,
# git на длинном списке получает SIGPIPE, конвейер возвращает 141 — и это читается как
# «совпадений нет». Поэтому сначала вывод в переменную, потом поиск. Ошибка git трактуется
# как «правка есть»: защитный механизм ошибается только в строгую сторону.
set -uo pipefail
REPO=$1; FROM=$2; TO=$3
CRITICAL='^(pipeline|checks|publish)\.py$|^run_daily\.sh$'   # пример: что считается путём выпуска
MARKS="$REPO/lab"

changed() {                       # есть ли в диапазоне правка критического пути
  local names
  names=$(git -C "$REPO" diff --name-only "$1" "$2" 2>/dev/null) || return 0
  grep -q -E "$CRITICAL" <<<"$names"
}

changed "$FROM" "$TO" || exit 0   # критический путь не тронут — прогон не нужен

for f in "$MARKS"/ok_*.json; do
  [ -f "$f" ] || continue
  sha=$(basename "$f" .json); sha=${sha#ok_}
  git -C "$REPO" merge-base --is-ancestor "$sha" "$TO" 2>/dev/null || continue
  changed "$sha" "$TO" && continue
  echo "лаборатория: ${sha:0:8} $(cat "$f")"
  exit 0
done
echo "правка критического пути без зелёного прогона лаборатории" >&2
exit 1
